#!/usr/bin/env bash
# Regenerate external/<crate>/lzcb_prefix.h: one guarded #define per symbol the built
# archive exports, renaming it into the lzcb_ namespace so this fork can be linked into
# a binary that also links the genuine library.
#
# Run on LINUX. macOS `nm` prepends an underscore to every C symbol, which would send
# every entry down the Mach-O branch below and corrupt the output.
#
#   ./tools/gen-symbol-prefix.sh zstd-sys liblzcb_zstd.a
#   ./tools/gen-symbol-prefix.sh lzma-sys liblzcb_lzma.a
#   ./tools/gen-symbol-prefix.sh lz4-sys liblzcb_lz4.a
set -euo pipefail

crate=$1
archive=$2
pkg="lzcb-${crate}"
cd "$(dirname "$0")/.."

# LZCB_NO_PREFIX breaks the bootstrap cycle: without it the only archive we could read
# is already prefixed.
cargo clean -p "$pkg"
LZCB_NO_PREFIX=1 cargo build -p "$pkg"
a=$(find target -path "*/build/${pkg}-*/out/${archive}" | head -1)
[ -n "$a" ] || { echo "no ${archive} built for ${pkg}" >&2; exit 1; }

{
  echo "/* GENERATED by tools/gen-symbol-prefix.sh from ${archive} -- do not edit."
  echo " *"
  echo " * Preprocessor-only on purpose: this header is force-included into every C"
  echo " * translation unit AND into zstd's .S file, which the C preprocessor also runs"
  echo " * over. Each entry is #ifndef-guarded so the header can be re-included to undo"
  echo " * a hostile #undef (see zstd_common.c)."
  echo " */"
  nm --defined-only --extern-only "$a" \
    | awk 'NF==3 { print $3 }' \
    | grep -v '^_\?lzcb_' \
    | sort -u \
    | while read -r s; do
        case "$s" in
          # Mach-O spelling of a dual-declared asm label: keep the leading underscore
          # outside the prefix, or the C caller's _lzcb_X will not find it.
          _*) p="_lzcb_${s#_}" ;;
           *) p="lzcb_${s}" ;;
        esac
        printf '#ifndef %s\n#define %s %s\n#endif\n' "$s" "$s" "$p"
      done
} > "external/${crate}/lzcb_prefix.h"

echo "wrote external/${crate}/lzcb_prefix.h ($(grep -c '^#define' "external/${crate}/lzcb_prefix.h") symbols)"
